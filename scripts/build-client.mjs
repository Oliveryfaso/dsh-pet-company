import {readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
const root=new URL('../',import.meta.url);
const entry=await readFile(new URL('src/client-entry.js',root),'utf8');
const relay=(await readFile(new URL('src/client-relay.js',root),'utf8')).replace('export function createRendererRelay','function createRendererRelay');
const marker='/*__RENDERER_RELAY__*/';
if(entry.split(marker).length!==2||/\b(?:import|export)\s/.test(relay))throw Error('Unexpected client source structure');
const ownedFiles=['compat/dsh-pet-feedback/feedback-styles.mjs','compat/dsh-pet-feedback/feedback-core.mjs','compat/dsh-pet-feedback/feedback-dom.mjs','vendor/dsh-pet-0.3.7/player.js','src/owned/view.js','src/owned/client.js'];
const owned=(await Promise.all(ownedFiles.map(async p=>(await readFile(new URL(p,root),'utf8')).replace(/^import .*;\n/gm,'').replace(/^export /gm,'')))).join('\n');
const output='/* Generated by scripts/build-client.mjs; edit src/client-entry.js and src/client-relay.js. */\n'+entry.replace(marker,relay).replace('/*__OWNED_CLIENT__*/',owned);
const destination=new URL('client.js',root);
if(process.argv.includes('--check')) {
  if(await readFile(destination,'utf8')!==output)throw Error('client.js is stale; run npm run build');
  console.log('Client bundle matches its sources');
} else {await writeFile(destination,output);console.log('Built '+fileURLToPath(destination));}
